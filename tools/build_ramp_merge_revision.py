"""Build a ramp-preserving working copy of the two-lane RTAB-Map database.

The source databases are opened read-only. Only a copied seed database is
updated. RTAB-Map reprocess is run separately on that seed so node-local grids,
the optimized graph and the global occupancy are regenerated by RTAB-Map.
"""

